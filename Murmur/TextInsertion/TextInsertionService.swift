import AppKit
import ApplicationServices

/// How text reached the app.
enum InsertionOutcome: Equatable {
    /// The app read the text from the clipboard (⌘V worked), or couldn't be
    /// checked.
    case pasted
    /// No app read the clipboard, but setting the selected text through the
    /// Accessibility API worked.
    case accessibility
    /// Neither worked. The text is left on the clipboard for a manual ⌘V.
    case copiedToClipboard
    /// The focused field is a password field, so nothing was inserted.
    case refusedSecureField
}

/// Inserts text into whatever app currently has keyboard focus: save the whole
/// clipboard, put the text on it, synthesize ⌘V, then restore the clipboard
/// 500 ms later.
///
/// Pasting is far more reliable across apps (Electron, web editors, Office)
/// than writing the AX `kAXSelectedText` attribute, which many apps silently
/// ignore, so AX is only the fallback. Requires Accessibility permission and no
/// App Sandbox.
///
/// To know whether ⌘V landed, the text goes on the clipboard as a promise: the
/// pasteboard asks Dictum for the string only when an app actually reads it.
/// No read within `pasteTimeout` means the paste went nowhere.
@MainActor
final class TextInsertionService {
    private let pasteboard = NSPasteboard.general

    /// Restore the original clipboard 500 ms after the paste.
    private let restoreDelay: Duration = .milliseconds(500)
    /// How long the app gets to read the text before Dictum decides ⌘V failed.
    /// The clipboard isn't restored before the app reads it, so a slow app
    /// (Word, Outlook) gets the dictation, never the old clipboard.
    private let pasteTimeout: Duration = .milliseconds(1000)

    /// The user's clipboard from before the earliest insert whose restore is
    /// still pending. An insert that starts inside that window must restore
    /// this, not the previous insert's text.
    private var pendingOriginal: Snapshot?
    private var insertGeneration = 0
    /// The promise behind the clipboard item we wrote, kept alive until replaced.
    private var activePromise: PastePromise?

    #if DEBUG
    /// Self-test only: skip the ⌘V so the Accessibility fallback runs.
    var skipsPasteForTesting = false
    #endif

    /// Whether we're allowed to synthesize keystrokes. Without Accessibility the
    /// synthetic ⌘V is a silent no-op, so the caller must check this and fall back.
    var isTrusted: Bool { AXIsProcessTrusted() }

    /// Whether keyboard focus is in a password field. Dictum never types there.
    func focusedFieldIsSecure() -> Bool {
        FocusedElement.current()?.isSecureTextField ?? false
    }

    /// Put text on the clipboard without pasting or restoring — the fallback when
    /// it can't be inserted, so the user can paste it manually with ⌘V.
    /// Marked concealed (it stays until the user pastes it, so not transient).
    func copyToClipboard(_ text: String) {
        guard !text.isEmpty else { return }
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        writePrivately(item, markers: [.concealed, .autoGenerated])
    }

    func insert(_ text: String) async -> InsertionOutcome {
        guard !text.isEmpty else { return .pasted }
        let focused = FocusedElement.current()
        if focused?.isSecureTextField == true { return .refusedSecureField }

        insertGeneration += 1
        let generation = insertGeneration
        let original = pendingOriginal ?? currentSnapshot()
        pendingOriginal = original

        let promise = PastePromise(text)
        let item = NSPasteboardItem()
        item.setDataProvider(promise, forTypes: [.string])
        writePrivately(item, markers: [.transient, .concealed, .autoGenerated])
        activePromise = promise
        // The pasteboard state we expect to still see at restore time. If it has
        // advanced, the user (or an app) copied something new during the window —
        // we must NOT clobber it with the old snapshot.
        let expectedChangeCount = pasteboard.changeCount

        let clock = ContinuousClock()
        let pastedAt = clock.now
        #if DEBUG
        if !skipsPasteForTesting { synthesizePaste() }
        #else
        synthesizePaste()
        #endif

        while !promise.wasRead, clock.now - pastedAt < pasteTimeout {
            try? await Task.sleep(for: .milliseconds(20))
        }

        var outcome = InsertionOutcome.pasted
        if !promise.wasRead {
            // Nothing read the clipboard, so ⌘V went nowhere.
            if let focused, await focused.insertText(text) {
                outcome = .accessibility
            } else {
                outcome = .copiedToClipboard
            }
        }

        let elapsed = clock.now - pastedAt
        if elapsed < restoreDelay { try? await Task.sleep(for: restoreDelay - elapsed) }

        // A newer insert started meanwhile; it owns the clipboard and the restore.
        guard generation == insertGeneration else { return outcome }
        pendingOriginal = nil
        if outcome == .copiedToClipboard {
            // Swap the promise for real data so it outlives Dictum, and drop the
            // transient marker: this copy is meant to stay.
            if pasteboard.changeCount == expectedChangeCount { copyToClipboard(text) }
            return outcome
        }
        restore(original, ifChangeCountIs: expectedChangeCount)
        return outcome
    }

    /// Copy the current selection to the pasteboard (⌘C) and return it, restoring
    /// the previous clipboard afterward. Used by Command Mode / Transforms.
    func readSelectionViaCopy() async -> String? {
        let snapshot = pendingOriginal ?? currentSnapshot()
        pasteboard.clearContents()
        let changeCountBefore = pasteboard.changeCount

        synthesizeCopy()
        try? await Task.sleep(for: .milliseconds(120))

        let didCopy = pasteboard.changeCount != changeCountBefore
        let copied = didCopy ? pasteboard.string(forType: .string) : nil
        // Only restore if nothing else has touched the pasteboard since our ⌘C —
        // otherwise we'd clobber a copy the user made during the window. The
        // expected count is our pre-copy count (no copy) or post-copy count.
        let expected = didCopy ? pasteboard.changeCount : changeCountBefore
        restore(snapshot, ifChangeCountIs: expected)
        return copied?.isEmpty == false ? copied : nil
    }

    // MARK: - Private clipboard writes

    /// Write an item Dictum generated, kept off other devices and out of
    /// clipboard histories:
    /// - `currentHostOnly` keeps it out of Universal Clipboard, so dictation
    ///   never syncs to an iPhone or another Mac.
    /// - The nspasteboard.org marker types tell clipboard managers (Raycast,
    ///   Maccy, Paste, Alfred…) not to record it. See http://nspasteboard.org.
    private func writePrivately(_ item: NSPasteboardItem, markers: [NSPasteboard.PasteboardType]) {
        for marker in markers { item.setData(Data(), forType: marker) }
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        pasteboard.writeObjects([item])
    }

    // MARK: - Pasteboard snapshot / restore

    private struct Snapshot {
        let items: [[NSPasteboard.PasteboardType: Data]]
    }

    /// Every item on the clipboard, with every type it offers.
    private func currentSnapshot() -> Snapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item -> [NSPasteboard.PasteboardType: Data] in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { dict[type] = data }
            }
            return dict
        }
        return Snapshot(items: items)
    }

    /// Restore a snapshot. When `expected` is given, restore only if the
    /// pasteboard hasn't changed since — so a copy the user made while the paste
    /// was in flight is preserved rather than overwritten.
    private func restore(_ snapshot: Snapshot, ifChangeCountIs expected: Int? = nil) {
        if let expected, pasteboard.changeCount != expected { return }
        pasteboard.clearContents()
        activePromise = nil
        guard !snapshot.items.isEmpty else { return }
        let items = snapshot.items.map { dict -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }

    // MARK: - Synthetic key events

    private func synthesizePaste() { synthesize(keyCode: 0x09) } // V
    private func synthesizeCopy() { synthesize(keyCode: 0x08) }  // C

    private func synthesize(keyCode: CGKeyCode) {
        // A *private* event source: the synthetic ⌘V reports only the Command flag
        // and ignores any physical modifier still held (e.g. the push-to-talk key
        // or ⌃⌥ from the toggle combo), which would otherwise corrupt the keystroke.
        let source = CGEventSource(stateID: .privateState)
        let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true)
        down?.flags = .maskCommand
        let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false)
        up?.flags = .maskCommand
        down?.post(tap: .cgAnnotatedSessionEventTap)
        // A brief gap between down and up — some apps drop a zero-duration ⌘V.
        usleep(1500)
        up?.post(tap: .cgAnnotatedSessionEventTap)
    }
}

/// The pasted text, handed to the pasteboard only when an app asks for it.
/// That request is how Dictum knows ⌘V reached an app. The pasteboard may call
/// in on any thread, so the flag is lock-protected.
private final class PastePromise: NSObject, NSPasteboardItemDataProvider, @unchecked Sendable {
    private let text: String
    private let lock = NSLock()
    private var read = false

    init(_ text: String) {
        self.text = text
    }

    var wasRead: Bool {
        lock.lock(); defer { lock.unlock() }
        return read
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .string else { return }
        item.setString(text, forType: .string)
        lock.lock(); read = true; lock.unlock()
    }
}

extension NSPasteboard.PasteboardType {
    /// The item will be removed shortly; clipboard managers shouldn't record it.
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    /// The item is sensitive (like a password); clipboard managers shouldn't record it.
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    /// The item was generated by an app, not copied by the user.
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
}
